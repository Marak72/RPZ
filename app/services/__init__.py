"""Сервисы портала — самостоятельные приложения внутри общей оболочки.

Каждый сервис живёт в одной папке и содержит ВСЁ, что к нему относится::

    services/<сервис>/
        __init__.py    точка входа: blueprint + регистрация моделей
        routes.py      страницы и действия
        forms.py       формы
        models.py      таблицы этого сервиса
        lib/           клиенты внешних систем этого сервиса
        templates/     шаблоны этого сервиса

Чтобы что-то поменять в сервисе, достаточно открыть его папку — ни в общем
ядре, ни в соседних сервисах править ничего не нужно.

Общее для всех лежит в ``app/core`` (база, шифрование, настройки, фоновые
задания, VirusTotal) и ``app/templates`` (базовая вёрстка портала).

Связи между сервисами допускаются, но только явные и узкие: сейчас это
единственный случай — «Угрозы SkyDNS» отправляет разобранный домен в
кандидаты «РПЗ ФСТЭК» (``services.fstec.models.BlockEntry``).
"""
